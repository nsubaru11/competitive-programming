	private static void solve() {
		int n = sc.nextInt();
		int m = sc.nextInt();
		long s = sc.nextLong0();
		long t = sc.nextLong0();
		int si = (int) (s / n), sj = (int) (s % n);
		int ti = (int) (t / n), tj = (int) (t % n);
		long[] p = sc.nextLong0(m);
		int[][] dist = new int[m][m];
		int[] distS = new int[m], distT = new int[m];
		for (int i = 0; i < m; i++) {
			int p1i = (int) (p[i] / n), p1j = (int) (p[i] % n);
			distS[i] = abs(p1i - si) + abs(p1j - sj);
			distT[i] = abs(p1i - ti) + abs(p1j - tj);
			for (int j = i + 1; j < m; j++) {
				int p2i = (int) (p[j] / n), p2j = (int) (p[j] % n);
				dist[i][j] = dist[j][i] = abs(p1i - p2i) + abs(p1j - p2j);
			}
		}
		int ans = Integer.MAX_VALUE;
		int[][] memo = new int[m][1 << m];
		for (int i = 0; i < m; i++) {
			ans = min(ans, distS[i] + dfs(i, 1 << i, dist, distT, memo, m));
		}
		out.println(ans == Integer.MAX_VALUE ? abs(si - ti) + abs(sj - tj) : ans);
	}

	private static int dfs(int i, int visited, int[][] dist, int[] distT, int[][] memo, int m) {
		if (memo[i][visited] != 0) return memo[i][visited];
		if (visited == (1 << m) - 1) return memo[i][visited] = distT[i];
		int ans = Integer.MAX_VALUE;
		for (int j = 0; j < m; j++) {
			if ((visited >> j & 1) == 1) continue;
			int next = visited | (1 << j);
			ans = min(ans, dist[i][j] + dfs(j, next, dist, distT, memo, m));
		}
		return memo[i][visited] = ans;
	}

